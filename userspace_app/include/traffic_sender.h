#ifndef TRAFFIC_SENDER_H
#define TRAFFIC_SENDER_H

/**
 * Интерфейс traffic_sender
 *
 * @ctx: контекст конкретной реализации (любая структура, необходимая для работы)
 * @send: функция, которая отправляет заранее подготовленный трафик
 * @destroy: функция, которая освобождает ресурсы
 *
 * send() должен возвращать 0 при успешной отправки и -1 при ошибке.
 * Также его можно вызывать многократно после одной инициализации
 *
 * destroy() закрывает дескрипторы и освобождает память конкретной реализации.
 */

struct traffic_sender {
    void *ctx;

    int (*send)(void* ctx);
    void (*destroy)(void*  ctx);
};

#endif